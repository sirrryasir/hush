#!/usr/bin/env python3
"""Turn lockscreen/layout.toml into the hyprlock widgets and the SDDM greeter's layout.qml.

  gen.py hyprlock OUT [NAME:HEIGHT ...]   one widget set per monitor (none given: one set for
                                          every monitor at H = 1080)
  gen.py qml OUT                          the same spec as a QML object for the greeter
"""
import os, sys, tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = tomllib.load(open(os.path.join(HERE, "layout.toml"), "rb"))
WEIGHTS = {100: "Thin", 200: "ExtraLight", 300: "Light", 400: "", 500: "Medium", 600: "SemiBold", 700: "Bold"}
ICONS = "Material Symbols Rounded"


def even(v):
    return int(2 * round(v / 2))


def pct(cy):  # hyprlock offset from the centre (+ up) as a % of the height
    return f"{(0.5 - cy) * 100:.3f}%"


def family(weight):
    return ("Inter Variable " + WEIGHTS[weight]).strip()


def hyprlock(monitors):
    S = SPEC
    b = S["blur"]
    out = [
        "# Generated by `hush` from lockscreen/layout.toml. Do not edit: run `hush reload`.",
        "background {",
        "    monitor =",
        "    path = $wall",
        f"    blur_passes = {b['passes']}",
        f"    blur_size = {b['size']}",
        f"    brightness = {b['brightness']}",
        f"    contrast = {b['contrast']}",
        f"    vibrancy = {b['vibrancy']}",
        f"    vibrancy_darkness = {b['vibrancy_darkness']}",
        f"    noise = {b['noise']}",
        "}",
    ]
    for name, h in monitors:
        s = h / S["base"]
        L = lambda v: even(v * s)
        F = lambda v: int(round(v * s))
        PT = lambda v: int(round(v * s * 0.75))  # hyprlock font_size is in points at 96 dpi
        c, d, p, a, f, g, st, m = (S[k] for k in ("clock", "date", "pill", "avatar", "field", "glyph", "status", "media"))
        pw, ph = L(p["w"]), L(p["h"])
        av = L(a["size"])
        av_x = -pw // 2 + L(a["inset"]) + av // 2
        gl_x = pw // 2 - L(g["inset"])
        track = int(round(c["tracking"] * s * 1024 * 0.75))  # px -> Pango units (1/1024 pt, 96 dpi)
        mon = f"    monitor = {name}"
        out += [
            f"\n# ---- {name or 'every monitor'} at H = {h} (s = {s:.4f})",
            "label { # clock, tabular figures",
            mon,
            f"    text = cmd[update:1000] echo \"<span font_features='tnum' letter_spacing='{track}'>$(date +%H:%M)</span>\"",
            "    color = $hushWallText",
            f"    font_size = {PT(c['size'])}",
            f"    font_family = {family(c['weight'])}",
            f"    position = 0, {pct(c['cy'])}",
            "    halign = center", "    valign = center",
            "}",
            "label { # date",
            mon,
            "    text = cmd[update:60000] date +\"%A, %-d %B\"",
            "    color = $hushWallMuted",
            f"    font_size = {PT(d['size'])}",
            f"    font_family = {family(d['weight'])}",
            f"    position = 0, {pct(d['cy'])}",
            "    halign = center", "    valign = center",
            "}",
            "shape { # the island pill",
            mon,
            "    zindex = 1",
            f"    size = {pw}, {ph}",
            "    color = $hushIslandBg",
            f"    rounding = {ph // 2}",
            "    border_size = 1",
            "    border_color = $hushIslandEdge",
            f"    position = 0, {pct(p['cy'])}",
            "    halign = center", "    valign = center",
            "}",
            "image { # avatar inside the pill (above the left cover)",
            mon,
            "    zindex = 5",
            "    path = $HOME/.cache/hush/face.png",
            f"    size = {av}",
            "    rounding = -1",
            "    border_size = 1",
            "    border_color = $hushIslandEdge",
            f"    position = {av_x}, {pct(p['cy'])}",
            "    halign = center", "    valign = center",
            "}",
            "input-field { # transparent, on top of the pill: only its hairline and dots show",
            mon,
            "    zindex = 3",
            f"    size = {pw}, {ph}",
            "    rounding = -1",
            "    outline_thickness = 1",
            f"    dots_size = {round(f['dot'] / p['h'], 3)}",
            f"    dots_spacing = {round(f['dot_gap'] / f['dot'], 3)}",
            "    dots_center = true",
            "    inner_color = $hushClear",
            "    outer_color = $hushIslandEdge",
            "    check_color = $hushIslandCheck",
            "    fail_color = $hushIslandFail",
            "    capslock_color = $hushIslandEdge",
            "    font_color = $hushIslandText",
            "    font_family = Inter Variable",
            "    fade_on_empty = false",
            f"    placeholder_text = <span alpha='60%' size='{int(round(f['placeholder'] * s * 0.75 * 1024))}'>Enter password</span>",
            "    fail_text =",
            "    fail_timeout = 600",
            "    hide_input = false",
            f"    position = 0, {pct(p['cy'])}",
            "    halign = center", "    valign = center",
            "}",
        ] + [
            line for cx in (-pw // 2 + ph // 2, pw // 2 - ph // 2) for line in (
                "shape { # black disc over a pill end: hyprlock spreads long passwords past the field, this",
                mon,  # keeps the dots between avatar and glyphs while the 1 px hairline stays visible
                "    zindex = 4",
                f"    size = {ph - 4}, {ph - 4}",
                "    color = $hushIslandBg",
                "    rounding = -1",
                "    border_size = 0",
                f"    position = {cx}, {pct(p['cy'])}",
                "    halign = center", "    valign = center",
                "}",
            )
        ] + [
            "label { # caps lock glyph, right end of the pill",
            mon,
            "    zindex = 5",
            "    text = cmd[update:250] $HOME/.config/hyprlock/caps-lock.sh",
            "    color = $hushIslandMuted",
            f"    font_size = {PT(g['size'])}",
            f"    font_family = {ICONS}",
            f"    position = {gl_x}, {pct(p['cy'])}",
            "    halign = center", "    valign = center",
            "}",
            "label { # fingerprint glyph while PAM waits for the sensor ($FPRINTPROMPT is empty without fprintd)",
            mon,
            "    zindex = 5",
            "    text = $FPRINTPROMPT",
            "    color = $hushIslandMuted",
            f"    font_size = {PT(g['size'])}",
            f"    font_family = {ICONS}",
            f"    position = {gl_x - L(g['size']) - L(8)}, {pct(p['cy'])}",
            "    halign = center", "    valign = center",
            "}",
            "label { # status: battery and network icons, top right",
            mon,
            "    text = cmd[update:10000] $HOME/.config/hyprlock/status-line.sh",
            "    color = $hushWallMuted",
            f"    font_size = {PT(st['size'])}",
            f"    font_family = {ICONS}",
            f"    position = {-L(st['right'])}, {-(L(st['top']) - F(st['size'] * 1.2) // 2)}",
            "    halign = right", "    valign = top",
            "}",
            "label { # media line, only while something plays",
            mon,
            "    text = cmd[update:2000] $HOME/.config/hyprlock/media-line.sh",
            "    color = $hushWallText",
            f"    font_size = {PT(m['size'])}",
            "    font_family = Inter Variable Medium",
            "    shadow_passes = 2",  # small text: a soft halo in the surface colour keeps it legible
            "    shadow_size = 4",
            "    shadow_color = $hushWallShade",
            f"    position = 0, {pct(m['cy'])}",
            "    halign = center", "    valign = center",
            "}",
        ]
    return "\n".join(out) + "\n"


def qml():
    lines = ["// Generated by `hush sddm sync` from lockscreen/layout.toml. The greeter falls back to",
             "// its baked defaults when this file is missing.", "import QtQuick", "QtObject {"]
    for sec, vals in SPEC.items():
        if not isinstance(vals, dict):
            lines.append(f"    property real {sec}: {vals}")
            continue
        for k, v in vals.items():
            parts = k.split("_")
            head = sec.split("_")
            name = head[0] + "".join(x.capitalize() for x in head[1:] + parts)
            lines.append(f"    property real {name}: {v}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 3 or argv[1] not in ("hyprlock", "qml"):
        sys.exit(__doc__)
    if argv[1] == "hyprlock":
        mons = [(a.rsplit(":", 1)[0], int(a.rsplit(":", 1)[1])) for a in argv[3:]] or [("", SPEC["base"])]
        text = hyprlock(mons)
    else:
        text = qml()
    if argv[2] == "-":
        sys.stdout.write(text)
        return
    tmp = argv[2] + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, argv[2])


if __name__ == "__main__":
    main(sys.argv)
